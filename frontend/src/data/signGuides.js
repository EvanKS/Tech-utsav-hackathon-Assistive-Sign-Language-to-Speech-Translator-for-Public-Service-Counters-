export function getSignGuide(signKey) {
  if (!signKey) return null;
  const key = signKey.trim();
  // Match exact, lower, or upper
  return SIGN_GUIDES[key] || SIGN_GUIDES[key.toLowerCase()] || SIGN_GUIDES[key.toUpperCase()] || null;
}
